"""Synthetic fixture branches whose expectations were produced by the legacy code.

``tests/fixtures/m4/synthetic/legacy_expected.json`` is generated by
``generate_legacy.py`` on Ubuntu-nnG8 with the live legacy runtime.  These tests never
hand-write an expected decision: they replay the same synthetic input through qp and
compare field by field with that artifact.
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path
from types import SimpleNamespace

import pytest

from qp.market.kline import DailyBar
from qp.signals.eod import Target, evaluate_target
from qp.signals.risk import gate_action

FIXTURE = Path(__file__).parent / "fixtures/m4/synthetic/legacy_expected.json"


@pytest.fixture(scope="module")
def legacy() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_fixture_pins_legacy_sources(legacy):
    assert legacy["schema_version"] == "1.0"
    for name, digest in legacy["legacy_source"].items():
        assert len(digest) == 64, name
        int(digest, 16)


def test_risk_gate_matrix_matches_legacy(legacy):
    targets = {row["code"]: row for row in legacy["risk_gate"]["targets"]}
    assert len(targets) >= 5
    for case in legacy["risk_gate"]["cases"]:
        risk_state = case["risk_state"]
        level = risk_state.get("level") if isinstance(risk_state, dict) else None
        expected = case["expected"]
        for code, target in targets.items():
            action = gate_action(level, target["sector"], target["name"])
            expected_action = "allowed" if code in expected["allowed"] else "blocked"
            assert action == expected_action, (case["level"], code, action)


def test_volume_breakout_matches_legacy(legacy):
    case = legacy["volume_breakout"]
    assert case["daily_breakout_enabled"] is True
    bars = [
        DailyBar(
            date=dt.date.fromisoformat(row["date"]),
            open=row["open"],
            high=row["high"],
            low=row["low"],
            close=row["close"],
            volume=row["volume"],
        )
        for row in case["bars"]
    ]
    decision_date = bars[-1].date

    class Fetcher:
        def get(self, code, *, required_date=None, previous_session=None):
            return SimpleNamespace(bars=bars, attempts=[], source="synthetic", publication_lag=False)

    target = Target(case["code"], case["name"], "宽基")
    evaluation = evaluate_target(target, Fetcher(), decision_date=decision_date, daily_breakout_enabled=True)
    assert evaluation.data_ok is True
    actual = [
        {
            "code": s.code,
            "name": s.name,
            "signal_type": s.signal_type,
            "period": s.period,
            "title": s.title,
            "detail": s.detail,
            "confidence": s.confidence,
        }
        for s in evaluation.signals
    ]
    assert actual == case["expected_signals"]
